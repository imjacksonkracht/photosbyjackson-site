// Writes docs/PHOTO-MANIFEST.md from the content files.
//   node scripts/photo-manifest.ts
//
// The manifest is public, so it lists public names only. Each row's source
// hash (first 12 characters of the original's SHA-1) traces it back to the
// original through the private photos/source-map.json.
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { allProjects as projects, categoryCovers, heroSlides, projectLabel, selectedWork, type Row } from "../content/projects.ts";

const root = path.resolve(import.meta.dirname, "..");
const generated = JSON.parse(readFileSync(path.join(root, "content/photos.generated.json"), "utf8"));
const photosTs = readFileSync(path.join(root, "content/photos.ts"), "utf8");

const alts: Record<string, string> = {};
for (const m of photosTs.matchAll(/"([a-z0-9-]+)":\s*\{\s*alt:\s*"((?:[^"\\]|\\.)*)"/g)) alts[m[1]] = m[2];

const placement = (row: Row) => row.kind;
const orientation = (g: { width: number; height: number }) => {
  const a = g.width / g.height;
  return a > 1.05 ? "landscape" : a < 0.95 ? "portrait" : "square";
};

const lines = [
  "# Photo manifest",
  "",
  "Generated by `node scripts/photo-manifest.ts`. Do not edit by hand.",
  "",
  "- Originals: `photos/` (private, gitignored, never modified).",
  "- Public files: `<path>-{640,1280,2048}.avif` and `<path>.webp`, metadata stripped.",
  "- Source hash: first 12 characters of the original's SHA-1. `photos/source-map.json` (private) maps each public name back to its original.",
  "",
];

for (const p of projects) {
  lines.push(`## ${p.title}`, "");
  lines.push(`- Route: \`/work/${p.slug}\` · Category: ${projectLabel(p)}${p.hidden ? " · **hidden from the site**" : ""}`);
  lines.push(`- Date: ${p.date ?? "not verified"} · Location: ${p.location ?? "not verified"}`);
  lines.push(`- Client gallery: ${p.galleryUrl ?? "none linked"} · Share image: ${p.hidden ? "none" : `\`/og/${p.slug}.jpg\``}`, "");
  lines.push("| Public name | Path | Size | Orientation | Placement | Also used | Source hash | Alt text |");
  lines.push("|---|---|---|---|---|---|---|---|");
  for (const row of p.sequence) {
    const ids = "photos" in row ? row.photos : [row.photo];
    for (const id of ids) {
      const g = generated[id];
      const also = [
        p.cover === id && "project cover",
        selectedWork.some((s) => s.photo === id) && "home: selected work",
        Object.values(categoryCovers).includes(id) && "home: category",
        heroSlides.some((h) => h.photo === id) && "home hero",
        id === "petty-theft-guitarist-silhouette-01" && "/og.jpg",
      ]
        .filter(Boolean)
        .join(", ");
      lines.push(
        `| \`${id}\` | \`${g.path}\` | ${g.width}×${g.height} | ${orientation(g)} | ${placement(row)} | ${also || "—"} | \`${g.sourceHash}\` | ${alts[id] ?? ""} |`,
      );
    }
  }
  lines.push("");
}

const about = generated["jackson-behind-the-scenes"];
if (about) {
  lines.push("## About page", "");
  lines.push("| Public name | Path | Size | Source hash | Alt text |", "|---|---|---|---|---|");
  lines.push(`| \`${about.id}\` | \`${about.path}\` | ${about.width}×${about.height} | \`${about.sourceHash}\` | ${alts[about.id] ?? ""} |`, "");
}

writeFileSync(path.join(root, "docs/PHOTO-MANIFEST.md"), lines.join("\n"));
console.log("docs/PHOTO-MANIFEST.md written");
